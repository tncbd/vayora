#!/usr/bin/env bash
# Builds two SQL Editor files from supabase/migrations/*.sql:
#   supabase/apply_all.sql      - every migration, for a FRESH project only
#   supabase/apply_phase4.sql   - only the migrations added in Phase 4 (20261104*), for a project that already has Phases 2-3
#   supabase/apply_phase5.sql   - only the Phase 5 migration (20261105*), for a project that already has Phases 2-4
set -euo pipefail
cd "$(dirname "$0")/.."
bundle() { # output, glob
  { echo "-- GENERATED by scripts/bundle-migrations.sh from supabase/migrations — do not edit."; for f in $2; do echo; echo "-- ===== $(basename "$f") ====="; cat "$f"; done; } > "$1"
  echo "wrote $1"
}
bundle supabase/apply_all.sql "supabase/migrations/*.sql"
bundle supabase/apply_phase4.sql "supabase/migrations/20261104*.sql"
bundle supabase/apply_phase5.sql "supabase/migrations/20261105000001*.sql"
bundle supabase/apply_phase6.sql "supabase/migrations/20261105000002*.sql"
bundle supabase/apply_phase7.sql "supabase/migrations/20261106000001*.sql"
bundle supabase/apply_phase8.sql "supabase/migrations/20261107000001*.sql"
bundle supabase/apply_phase9.sql "supabase/migrations/20261108000001*.sql"
bundle supabase/apply_phase10.sql "supabase/migrations/20261109000001*.sql"
