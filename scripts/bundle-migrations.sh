#!/usr/bin/env bash
# Concatenate all migrations, in order, into one file for the Supabase SQL Editor.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/apply_all.sql
{ echo "-- GENERATED by scripts/bundle-migrations.sh from supabase/migrations/*.sql — do not edit."; for f in supabase/migrations/*.sql; do echo; echo "-- ===== $(basename "$f") ====="; cat "$f"; done; } > "$out"
echo "wrote $out"
